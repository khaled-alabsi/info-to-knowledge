"""A grid of cameras beside a share is cut off, decided on scenes rendered from HTML pages with public-domain portraits
(`tests/resources/scenes/`, regenerated by its `render.sh`) and read by the real face detector.

Teams on the web in a light theme shows the share framed on a white stage, with the cameras two wide on its right. The
stage is not black, so only the panel rule can cut the cameras off; the face detector finds a few of them, and the
panel rule wanted two faces stacked in one column and searched from the outer column, which ended before the share's
border. One scene has no two faces stacked, the other a stack in the outer column and a face in the inner one, the
faces smaller.
"""

from pathlib import Path

import tempfile

import cv2

from support import harness

import config

from models import screen_box
from services import frame_extraction_service

SCENES = Path(__file__).resolve().parents[1] / "resources" / "scenes"
TOLERANCE_PX = 12
SHARE_RIGHT = 2896                          # the share's right border at twice the pixels: 108 + 1340 on the page
EXPECTED = (("call-share-camera-grid.png", "a share beside a grid of cameras, no two faces found stacked"),
            ("call-share-camera-grid-stacked.png", "a share beside a grid of cameras, two faces stacked in the outer column"))


def test_a_grid_of_cameras_beside_a_share_is_cut_at_the_share():
    if not all((SCENES / name).is_file() for name, _ in EXPECTED):
        print(f"scenes not rendered: run {SCENES / 'render.sh'} (needs Chrome and the network once): skipped")
        return
    for name, label in EXPECTED:
        frame = cv2.imread(str(SCENES / name))
        found = frame_extraction_service._find_shared_screen(frame, cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)).box
        is_cut = found != screen_box.NO_SCREEN and abs(found[2] - SHARE_RIGHT) <= TOLERANCE_PX
        harness.check(f"{label}: cut at the share's right border", is_cut, f"found {found}, border {SHARE_RIGHT}")


def test_the_capture_loop_keeps_the_grid_cut_while_the_faces_it_sees_change():
    """The whole phase 2 loop over a video of the scenes: faces in both columns, then in the outer column only, the
    share's list changing once. A run cut each frame right alone and still took the whole call window: the outer
    column's faces alone reached no edge, and two such checks in a row put the window back as the box; and the share's
    border and the panel's divider beside it were equally strong, so the cut flipped between them (2026-10-10)."""

    video = SCENES / "loop-grid.mp4"
    if not video.is_file():
        print(f"scene video not built: run {SCENES / 'render.sh'} (needs Chrome and ffmpeg): skipped")
        return
    frames = frame_extraction_service.extract_frames(video, Path(tempfile.mkdtemp()) / "frames",
                                                     config.FrameSettings(mode="change", max_count=1000, max_width=640))
    rights = [item["screenBox"][2] for item in frames["items"]]
    harness.check("the loop takes a frame of each share list", len(rights) >= 2, str(rights))
    harness.check("every frame taken is cut at the share's right border",
                  all(abs(right - SHARE_RIGHT) <= TOLERANCE_PX for right in rights), f"right edges {rights}")
