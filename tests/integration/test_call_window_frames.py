"""A call window is no shared screen, decided on scenes rendered from HTML pages with public-domain portraits
(`tests/resources/scenes/`, regenerated by its `render.sh`) and read by the real face detector and text reader.

A browser-based meeting's gallery, people sitting back from their cameras and tiles holding initials instead of a
camera, passed both face rules: two faces covered 1.9% of the crop where a gallery needs 2.5%, and the browser's own
words counted as content; a crop of two of its tiles held one face at 1.28% where a lone camera needs 1.5%. Each
scene that must stay a screen sits beside them: a slide with a photo, a list of nouns with commas, two noun pairs
apart on a dense slide, an author written "<Last>, <First>", a slide introducing two people by name.
"""

from pathlib import Path

import cv2

from support import harness

from models import screen_box
from services import frame_extraction_service
from services import text_detection_service

SCENES = Path(__file__).resolve().parents[1] / "resources" / "scenes"
# Each rendered scene, whether it is a call window (no screen), and what it is
EXPECTED = (("call-gallery.png", True, "a browser call's gallery: two cameras with people sitting back, two tiles of initials"),
            ("call-two-tiles.png", True, "a crop of two of its tiles: one camera, one tile of initials"),
            ("slide-photo.png", False, "a slide with a photo and its caption"),
            ("slide-noun-list.png", False, "a slide listing nouns with commas beside a photo"),
            ("slide-noun-pairs-apart.png", False, "a dense slide with two noun pairs apart beside a photo"),
            ("slide-author.png", False, "a slide naming its author as surname, first name beside a photo"),
            ("slide-team.png", False, "a slide introducing two people by name"))


def test_a_call_window_is_no_screen_and_a_slide_with_people_on_it_stays_one():
    if not text_detection_service.is_available():
        harness.check("the text reader is needed: skipped", True)
        return
    # The scenes are in git beside their pages; `render.sh` renders them again after a page changes
    if not all((SCENES / name).is_file() for name, _, _ in EXPECTED):
        print(f"scenes not rendered: run {SCENES / 'render.sh'} (needs Chrome and the network once): skipped")
        return
    for name, is_call, label in EXPECTED:
        frame = cv2.imread(str(SCENES / name))
        found = frame_extraction_service._find_shared_screen(frame, cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)).box
        harness.check(f"{label}: {'no screen' if is_call else 'still a screen'}",
                      (found == screen_box.NO_SCREEN) == is_call, str(found))
