"""A presenter's camera floating in a corner of the shared screen is found and covered, decided on scenes rendered from
HTML pages with public-domain portraits (`tests/resources/scenes/`, regenerated by its `render.sh`) and read by the
real face detector.

A Teams recording draws the speaker's camera over the top-right corner of a share; the frame was taken with the face
on it. Each tile scene must stay a screen, its tile found and covered so no face is left there; every other scene, a
slide with a photo among them, must have no tile.
"""

from pathlib import Path

import cv2

from support import harness

from models import screen_box
from services import face_detection_service
from services import frame_extraction_service
from utils import screen_crop_utils

SCENES = Path(__file__).resolve().parents[1] / "resources" / "scenes"
TOLERANCE_PX = 12
# Each rendered scene with a tile, the tile it holds at twice the pixels (288 x 162 on a 1728 x 1117 page), and what it is
TILE_SCENES = (("browser-camera-tile.png", (2880, 0, 3456, 324),
                "a browser page with the camera at the top right, coloured rows of the page under it"),
               ("slide-camera-tile-bottom-left.png", (0, 1910, 576, 2234), "a slide with the camera at the bottom left"),
               ("lecture-terminal-camera-inset.png", (2544, 760, 3408, 1246),
                "a dark terminal with a lecture's room camera at the middle of its right edge (DEFECTS 91, 103)"))
OTHER_SCENES = ("call-gallery.png", "call-two-tiles.png", "slide-photo.png", "slide-noun-list.png",
                "slide-noun-pairs-apart.png", "slide-author.png", "slide-team.png",
                "loop-lecture-walk-a.png", "loop-lecture-walk-c.png")


def _read_scene(name: str):
    frame = cv2.imread(str(SCENES / name))

    return frame, frame_extraction_service._find_shared_screen(frame, cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY))


def test_a_camera_in_a_corner_is_covered_and_no_other_scene_has_one():
    # The scenes are in git beside their pages; `render.sh` renders them again after a page changes
    names = [name for name, _, _ in TILE_SCENES] + list(OTHER_SCENES)
    if not all((SCENES / name).is_file() for name in names):
        print(f"scenes not rendered: run {SCENES / 'render.sh'} (needs Chrome and the network once): skipped")
        return
    for name, expected, label in TILE_SCENES:
        frame, found = _read_scene(name)
        harness.check(f"{label}: still a screen", found.box != screen_box.NO_SCREEN, str(found.box))
        is_found = found.tile is not None and all(abs(a - b) <= TOLERANCE_PX for a, b in zip(found.tile, expected))
        harness.check(f"{label}: its tile is found", is_found, f"found {found.tile}, expected {expected}")
        if found.tile is not None:
            covered = screen_crop_utils.cover_camera_tile(frame, found.tile)
            x0, y0, x1, y1 = found.tile
            faces = face_detection_service.detect_faces(cv2.cvtColor(covered[y0:y1, x0:x1], cv2.COLOR_BGR2GRAY))
            harness.check(f"{label}: no face is left in the covered tile", faces == [], str(faces))
    for name in OTHER_SCENES:
        _, found = _read_scene(name)
        harness.check(f"{name}: no camera tile", found.tile is None, str(found.tile))
